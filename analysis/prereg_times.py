"""When each pre-registration was committed: a table from the git history (no analysis).

Usage: py -I -X utf8 analysis/prereg_times.py > prereg/TIMES.md

For every file prereg/NN-*.md from 02 on: the freeze time its own status line states, and every commit that touched
the file (abbreviated hash and author time, in the time zone of the commit). The first commit of a file is the one
that added it; later ones are dated amendments, except where Appendix F of the paper says otherwise (the two
earliest files were edited in place the evening they were written). The table is generated, so it can be compared
with `git log --follow prereg/<file>` in a clone that carries this history.
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def commits(path):
    out = subprocess.run(['git', 'log', '--follow', '--format=%h|%ad', '--date=format:%Y-%m-%d %H:%M:%S %z', '--', path],
                         cwd=ROOT, capture_output=True).stdout.decode('utf-8', 'replace')
    return [tuple(line.split('|', 1)) for line in out.splitlines() if '|' in line][::-1]


def stated(text):
    m = re.search(r'FROZEN on ([A-Z][a-z]{2} \d{1,2}, \d{4}, (?:about )?\d{1,2}:\d{2} [AP]M [A-Z]{3})', text)
    return m.group(1) if m else 'not stated in one line'


def main():
    sys.stdout.reconfigure(encoding='utf-8', errors='replace', newline='\n')
    print('# Commit times of the pre-registrations')
    print()
    print('Generated by `analysis/prereg_times.py` from the git history. "Stated" is the freeze time in the file\'s own')
    print('status line; the commits are every commit that touched the file, oldest first (hash, author time).')
    print()
    print('| Pre-registration | Stated | Commits |')
    print('|---|---|---|')
    for p in sorted((ROOT / 'prereg').glob('[0-9][0-9]-*.md')):
        if p.name.startswith('01-'):
            continue
        cs = commits(f'prereg/{p.name}')
        print(f'| `{p.name}` | {stated(p.read_text(encoding="utf-8"))} | '
              + '; '.join(f'`{h}` {d}' for h, d in cs) + ' |')


if __name__ == '__main__':
    main()
